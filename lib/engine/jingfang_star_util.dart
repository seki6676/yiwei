  /// 获取某一卦的所有星宿列表
  /// [guaName] 传入卦名全称 (如"天风姤") 或简称 (如"姤") 均可
  static List<String> getStarsForGua(String guaName) {
    String shortName = _extractShortName(guaName);
    return _starMap[shortName] ?? List.filled(6, ''); // 查不到时返回6个空字符串防崩
  }

  /// 提取 64 卦的简称，用于精准匹配 Map 的 Key
  static String _extractShortName(String fullName) {
    const doubleChars = ['既济', '未济', '小畜', '大畜', '小过', '大过', '无妄', '噬嗑', '同人', '家人', '明夷', '归妹', '中孚'];
    for (String dc in doubleChars) {
      if (fullName.contains(dc)) return dc;
    }
    return fullName.substring(fullName.length - 1); // 默认取最后一个字
  }
